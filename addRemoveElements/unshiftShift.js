let fruitsArray=["apple","mango","banana","grapes","orange"];
console.log(`initial array: ${fruitsArray}`);
fruitsArray.unshift("peach"); //unshift array kay start may value add karta hay
console.log(`after unshift: ${fruitsArray}`);
fruitsArray.shift(); //array kay start may say element remove karta hay
console.log(`after shift: ${fruitsArray}`);